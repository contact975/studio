/**
 * ทำเนียบนักศึกษาฝึกงาน — แหล่งข้อมูลเดียวของหน้า /internship
 *
 * ── ทำไมแยกเป็นไฟล์นี้ ──
 * ข้อมูลนักศึกษาเปลี่ยนทุกรุ่น (ปีละ 1-2 ครั้ง) คนที่มาอัปเดตอาจไม่ใช่คนเขียนโค้ด
 * แยกออกมาเพื่อให้เพิ่มรุ่นใหม่ได้โดยแตะไฟล์เดียว ไม่ต้องยุ่งกับหน้าเว็บ
 *
 * ── วิธีเพิ่มรุ่นใหม่ ──
 * 1. เพิ่ม object ใหม่ไว้บนสุดของ COHORTS (รุ่นล่าสุดอยู่บน)
 * 2. รูปถ่าย: อัปโหลดไว้ที่ public/images/interns/ แล้วใส่พาธ เช่น '/images/interns/2569-01.jpg'
 *    ถ้ายังไม่มีรูป เว้น photo ไว้ได้ ระบบจะแสดงอักษรย่อของชื่อแทน
 *
 * ── เรื่องความเป็นส่วนตัว ──
 * หน้านี้เผยแพร่ชื่อและรูปของนักศึกษาสู่สาธารณะ ต้องได้รับความยินยอมจากเจ้าตัวก่อน
 * ตาม พ.ร.บ.คุ้มครองข้อมูลส่วนบุคคล (PDPA) และไม่ควรใส่ข้อมูลที่ไม่จำเป็น
 * เช่น เลขบัตรประชาชน เบอร์โทร หรืออีเมลส่วนตัว
 */

export type Intern = {
  /** ชื่อ-นามสกุล ตามที่นักศึกษายินยอมให้เผยแพร่ */
  name: string;
  /** ชื่อสถาบัน เช่น 'มหาวิทยาลัยแม่โจ้' */
  university: string;
  /** ระดับการศึกษา เช่น 'ปริญญาตรี' หรือ 'ปวส.' */
  level: string;
  /** สาขาวิชา (ถ้ามี) เช่น 'การบัญชี' */
  major?: string;
  /** พาธรูปใน public/ — ถ้าไม่มีจะแสดงอักษรย่อแทน */
  photo?: string;
};

export type InternCohort = {
  /** ปี พ.ศ. ของรุ่น ใช้เป็น key และหัวข้อ */
  year: string;
  /** ช่วงเวลาที่ฝึกงาน เช่น 'พฤศจิกายน 2568 – มีนาคม 2569' */
  period?: string;
  interns: Intern[];
};

/**
 * รุ่นล่าสุดอยู่บนสุด
 *
 * ⚠️ ยังไม่มีข้อมูลจริง — รอรายชื่อจากทีมงาน
 * โครงสร้างข้างล่างเป็นตัวอย่างรูปแบบที่ต้องกรอก (คอมเมนต์ไว้ ยังไม่แสดงผล)
 *
 * {
 *   year: '2569',
 *   period: 'พฤศจิกายน 2568 – มีนาคม 2569',
 *   interns: [
 *     { name: 'ชื่อ นามสกุล', university: 'มหาวิทยาลัยแม่โจ้', level: 'ปริญญาตรี', major: 'การบัญชี', photo: '/images/interns/2569-01.jpg' },
 *   ],
 * },
 */
export const COHORTS: InternCohort[] = [];

/** จำนวนนักศึกษาทั้งหมดที่เคยฝึกงานกับเรา — ใช้แสดงในหน้าเว็บ */
export const TOTAL_INTERNS = COHORTS.reduce((sum, c) => sum + c.interns.length, 0);

/** รายชื่อสถาบันที่เคยส่งนักศึกษามาฝึก (ไม่ซ้ำ) เรียงตามตัวอักษร */
export const PARTNER_UNIVERSITIES = [
  ...new Set(COHORTS.flatMap((c) => c.interns.map((i) => i.university))),
].sort((a, b) => a.localeCompare(b, 'th'));

